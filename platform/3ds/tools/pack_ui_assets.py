"""Resize editable generated PNGs and embed indexed UI artwork for 3DS.

Requires Pillow. Run from the repository root after editing new UI elements.
"""
from pathlib import Path
import struct
import zlib
from PIL import Image

root = Path(__file__).resolve().parents[3]
folder = root / 'new UI elements'
palette = (root / 'ui-assets/palette.pal').read_bytes()
pal = Image.new('P', (1, 1))
pal.putpalette([v * 4 for v in palette])
specs = [('panel-top', 380, 220), ('panel-bottom', 320, 240)] + [(f'button-{s}', 144, 40) for s in ['default', 'focused', 'pressed', 'disabled']]
header = ['// SPDX-License-Identifier: GPL-2.0-or-later', '// Generated by platform/3ds/tools/pack_ui_assets.py; edit the PNG sources.', '#pragma once', '#include <cstddef>', '#include <cstdint>', 'namespace fheroes2::threeDSUIAssets {', 'struct Asset { int width; int height; const uint8_t * data; size_t size; };']
for name, w, h in specs:
    # Source masters are retained; exact-size artwork remains editable too.
    target = folder / f'{name}.png'
    image = Image.open(target if target.exists() else folder / 'source' / f'{name}.png').convert('RGB')
    image = image.resize((w, h), Image.Resampling.LANCZOS)
    image.save(target)
    pixels = image.quantize(palette=pal, dither=Image.Dither.NONE).tobytes()
    packed = zlib.compress(pixels, 9)
    symbol = name.replace('-', '_')
    header.append(f'inline constexpr uint8_t {symbol}_data[] = {{')
    for i in range(0, len(packed), 32):
        header.append(','.join(str(b) for b in packed[i:i+32]) + ',')
    header.append('};')
    header.append(f'inline constexpr Asset {symbol}{{ {w}, {h}, {symbol}_data, sizeof({symbol}_data) }};')
header.append('}')
(root / 'src/engine/ui_3ds_assets.h').write_text('\n'.join(header) + '\n')
print('Packed six generated UI assets into src/engine/ui_3ds_assets.h')
